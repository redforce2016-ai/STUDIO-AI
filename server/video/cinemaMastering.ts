function clamp01(v: number): number {
  return Math.max(0, Math.min(1, v));
}

function smoothstep(edge0: number, edge1: number, x: number): number {
  const t = clamp01((x - edge0) / (edge1 - edge0));
  return t * t * (3 - 2 * t);
}

/**
 * Generates a real 33x33x33 Adobe/DaVinci Resolve .cube 3D LUT file.
 * Adobe .cube spec: R varies fastest, G middle, B slowest.
 */
export function generateCube3dLutText(preset: CinemaLookPreset): string {
  const size = 33;
  const titleMap: Record<CinemaLookPreset, string> = {
    industrial_teal_amber: "ContentStudio_Industrial_Teal_Amber_v1",
    kodak_2383_film: "ContentStudio_Kodak_2383_Print_v1",
    documentary_clean: "ContentStudio_Documentary_Rec709_v1",
    none: "ContentStudio_Identity_v1",
  };

  const lines: string[] = [
    `TITLE "${titleMap[preset]}"`,
    `# Generated by Content Studio CinemaMasteringEngine (Open-Source Headless Color Pipeline)`,
    `LUT_3D_SIZE ${size}`,
    `DOMAIN_MIN 0.0 0.0 0.0`,
    `DOMAIN_MAX 1.0 1.0 1.0`,
  ];

  for (let bi = 0; bi < size; bi++) {
    const b0 = bi / (size - 1);
    for (let gi = 0; gi < size; gi++) {
      const g0 = gi / (size - 1);
      for (let ri = 0; ri < size; ri++) {
        const r0 = ri / (size - 1);
        const luma = 0.2126 * r0 + 0.7152 * g0 + 0.0722 * b0;

        let r = r0;
        let g = g0;
        let b = b0;

        if (preset === "industrial_teal_amber") {
          // Filmic S-curve toe + shoulder rolloff matching glowing amber metal against deep teal-charcoal shadows
          const sCurve = (x: number) => {
            const contrasted = smoothstep(0.02, 0.98, x);
            return 0.72 * contrasted + 0.28 * x;
          };
          r = sCurve(r0);
          g = sCurve(g0);
          b = sCurve(b0);

          const shadowWeight = Math.pow(1 - luma, 1.8);
          const midWeight = Math.max(0, 1 - Math.abs(luma - 0.5) * 2.1);
          const highWeight = Math.pow(luma, 1.35);

          // Cool teal shadows, warm molten amber highlights
          r = r - 0.055 * shadowWeight + 0.085 * highWeight + 0.02 * midWeight;
          g = g + 0.012 * shadowWeight + 0.028 * highWeight;
          b = b + 0.058 * shadowWeight - 0.095 * highWeight - 0.015 * midWeight;

          // Subtle saturation polish around luma
          const lum2 = 0.2126 * r + 0.7152 * g + 0.0722 * b;
          const satBoost = 1.12;
          r = lum2 + (r - lum2) * satBoost;
          g = lum2 + (g - lum2) * satBoost;
          b = lum2 + (b - lum2) * satBoost;
        } else if (preset === "kodak_2383_film") {
          // Warm vintage cinema print emulation (deep rich blacks, creamy highlights)
          const printCurve = (x: number) => 0.015 + 0.97 * (0.78 * smoothstep(0.03, 0.97, x) + 0.22 * x);
          r = printCurve(r0);
          g = printCurve(g0);
          b = printCurve(b0);

          const shadowW = Math.pow(1 - luma, 1.6);
          const highW = Math.pow(luma, 1.4);
          r = r - 0.018 * shadowW + 0.055 * highW;
          g = g + 0.004 * shadowW + 0.018 * highW;
          b = b + 0.025 * shadowW - 0.068 * highW;
        } else if (preset === "documentary_clean") {
          // Clean crisp broadcast Rec.709 S-curve without strong tinting
          const crisp = (x: number) => 0.48 * smoothstep(0.01, 0.99, x) + 0.52 * x;
          r = crisp(r0);
          g = crisp(g0);
          b = crisp(b0);
        }

        lines.push(`${clamp01(r).toFixed(6)} ${clamp01(g).toFixed(6)} ${clamp01(b).toFixed(6)}`);
      }
    }
  }

  return lines.join("\n") + "\n";
}

export function generateCube3dLutFile(preset: CinemaLookPreset, outPath: string): string {
  fs.mkdirSync(path.dirname(outPath), { recursive: true });
  fs.writeFileSync(outPath, generateCube3dLutText(preset), "utf-8");
  return outPath;
}

/**
 * Multi-node open-source FFmpeg Cinema Mastering filtergraph (headless Linux replacement for DaVinci Color page):
 *  1) 33^3 3D LUT color transform (`lut3d`)
 *  2) Primary color balance + tonal contrast
 *  3) Highlight Halation / Molten Glow (`split -> lutyuv threshold -> gblur -> blend=screen`)
 *  4) Organic 35mm film grain (`noise=alls=3.5:allf=t+u`)
 *  5) Optical sharpening (`unsharp`) + subtle cinema `vignette`
 *  6) Optional Persian RTL burned subtitles
 */
export function buildCinemaVideoFilterGraph(params: {
  inputLabel?: string;
  outputLabel?: string;
  preset: CinemaLookPreset;
  cubeLutPath?: string | null;
  srtPath?: string | null;
  assPath?: string | null;
  fontsDir?: string | null;
  burnSubtitles?: boolean;
  enableHalation?: boolean;
  enableGrain?: boolean;
}): string {
  const inLbl = params.inputLabel || "[0:v]";
  const outLbl = params.outputLabel || "[v_grade]";
  const preset = params.preset || "industrial_teal_amber";

  const buildSubtitleFilter = (): string | null => {
    if (!params.burnSubtitles) return null;
    const esc = (p: string) => p.replace(/\\/g, "/").replace(/:/g, "\\:").replace(/'/g, "\\'");
    if (params.assPath && fs.existsSync(params.assPath)) {
      const fDir = params.fontsDir && fs.existsSync(params.fontsDir) ? `:fontsdir='${esc(params.fontsDir)}'` : "";
      return `ass=filename='${esc(params.assPath)}'${fDir}`;
    }
    if (params.srtPath) {
      const fDir = params.fontsDir && fs.existsSync(params.fontsDir) ? `:fontsdir='${esc(params.fontsDir)}'` : "";
      return `subtitles='${esc(params.srtPath)}'${fDir}:force_style='FontName=Vazirmatn,FontSize=13,Bold=1,PrimaryColour=&H00FFFFFF,OutlineColour=&H000C1018,BackColour=&H88000000,BorderStyle=1,Outline=2.2,Shadow=1.6,Alignment=2,MarginL=24,MarginR=24,MarginV=56'`;
    }
    return null;
  };

  const subtitleStage = buildSubtitleFilter();

  if (preset === "none") {
    if (subtitleStage) {
      return `${inLbl}${subtitleStage},format=yuv420p${outLbl}`;
    }
    return `${inLbl}null${outLbl}`;
  }

  const gradeStages: string[] = [];
  if (params.cubeLutPath && fs.existsSync(params.cubeLutPath)) {
    const escapedLut = params.cubeLutPath.replace(/\\/g, "/").replace(/:/g, "\\:");
    gradeStages.push(`lut3d=file='${escapedLut}':interp=tetrahedral`);
  }

  if (preset === "industrial_teal_amber") {
    gradeStages.push("colorbalance=rs=-0.03:bs=0.04:rh=0.05:bh=-0.05");
  } else if (preset === "kodak_2383_film") {
    gradeStages.push("colorbalance=rs=-0.01:bs=0.02:rh=0.04:bh=-0.04");
  } else {
    gradeStages.push("eq=contrast=1.04:saturation=1.06");
  }

  const parts: string[] = [];
  let currentLabel = "[v_lut]";
  parts.push(`${inLbl}${gradeStages.join(",")},format=yuv420p${currentLabel}`);

  const useHalation = params.enableHalation ?? preset !== "documentary_clean";
  if (useHalation) {
    const opacity = preset === "industrial_teal_amber" ? "0.22" : "0.15";
    parts.push(
      `${currentLabel}split=2[v_base][v_hi_src]`,
      `[v_hi_src]lutyuv=y='if(gt(val,188),val,0)':u=128:v=128,gblur=sigma=12,format=yuv420p[v_glow]`,
      `[v_base][v_glow]blend=all_mode=screen:all_opacity=${opacity},format=yuv420p[v_hal]`
    );
    currentLabel = "[v_hal]";
  }

  const finishStages: string[] = [];
  if (params.enableGrain ?? true) {
    finishStages.push("noise=alls=2.8:allf=t+u");
  }
  finishStages.push("unsharp=5:5:0.55:3:3:0.0");
  // Note: Omit FFmpeg `vignette` because elliptical angle clipping cuts black oval corners on 9:16 portrait Reels.
  if (subtitleStage) {
    finishStages.push(subtitleStage);
  }
  finishStages.push("format=yuv420p");

  parts.push(`${currentLabel}${finishStages.join(",")}${outLbl}`);
  return parts.join(";");
}

/**
 * Generates a cinematic background underscore WAV:
 *  1) Tries Google Lyria (`lyria-3-clip-preview` via `generateContentStream`) when API key is configured.
 *  2) Falls back gracefully to a rich multi-harmonic orchestral/industrial cinema drone synthesized in FFmpeg
 *     (never a monotone 110Hz beep!).
 */
export async function generateCinemaAmbientMusicBed(params: {
  outputPath: string;
  durationSec: number;
  moodPrompt?: string;
  preferLyria?: boolean;
}): Promise<{ musicPath: string; source: "lyria" | "ambient_cinema" }> {
  fs.mkdirSync(path.dirname(params.outputPath), { recursive: true });
  const dur = Math.max(2, Math.min(180, params.durationSec));
  const apiKey = getGoogleApiKeyFromRouter();

  if (params.preferLyria !== false && apiKey) {
    try {
      const ai = new GoogleGenAI({
        apiKey,
        apiVersion: "v1beta",
        httpOptions: {
          apiVersion: "v1beta",
          headers: { "User-Agent": "aistudio-build" },
        },
      });
      const prompt =
        params.moodPrompt?.trim() ||
        "Instrumental cinematic documentary score with warm low cello, subtle metallic industrial percussion pulse, atmospheric pads, modern engineering tension, no vocals.";

      const stream = await ai.models.generateContentStream({
        model: "lyria-3-clip-preview",
        contents: prompt,
      });

      let audioBase64 = "";
      let mimeType = "audio/wav";
      for await (const chunk of stream) {
        const parts = chunk.candidates?.[0]?.content?.parts;
        if (!parts) continue;
        for (const p of parts) {
          if (p.inlineData?.data) {
            if (!audioBase64 && p.inlineData.mimeType) mimeType = p.inlineData.mimeType;
            audioBase64 += p.inlineData.data;
          }
        }
      }

      if (audioBase64.length > 1000) {
        const rawExt = mimeType.includes("mpeg") || mimeType.includes("mp3") ? "mp3" : "wav";
        const rawPath = params.outputPath.replace(/\.wav$/i, `_lyria_raw.${rawExt}`);
        fs.writeFileSync(rawPath, Buffer.from(audioBase64, "base64"));

        // Loop / trim to exact project duration with clean fade-in/out
        await execFileAsync("ffmpeg", [
          "-y",
          "-stream_loop",
          "-1",
          "-i",
          rawPath,
          "-t",
          dur.toFixed(2),
          "-af",
          `aresample=48000,aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo,afade=t=in:st=0:d=0.6,afade=t=out:st=${Math.max(0.5, dur - 0.8).toFixed(2)}:d=0.8`,
          "-c:a",
          "pcm_s16le",
          params.outputPath,
        ]);
        try {
          fs.unlinkSync(rawPath);
        } catch {
          // ignore
        }
        if (fs.existsSync(params.outputPath)) {
          return { musicPath: params.outputPath, source: "lyria" };
        }
      }
    } catch {
      // Fall back cleanly to rich multi-harmonic procedural cinema underscore
    }
  }

  // Rich multi-harmonic orchestral/industrial ambient cinema bed (C2=65.41Hz + G2=98Hz + C3=130.81Hz + D3=146.83Hz + G3=196Hz + warm filtered noise)
  const fadeOutStart = Math.max(0.5, dur - 0.8).toFixed(2);
  const bgmFilter = [
    `anoisesrc=color=pink:sample_rate=48000:duration=${dur.toFixed(2)},lowpass=f=240,volume=0.14[noise_bed]`,
    `sine=frequency=65.41:sample_rate=48000:duration=${dur.toFixed(2)},volume=0.30[sub]`,
    `sine=frequency=98.00:sample_rate=48000:duration=${dur.toFixed(2)},volume=0.22[fifth]`,
    `sine=frequency=130.81:sample_rate=48000:duration=${dur.toFixed(2)},volume=0.18[oct]`,
    `sine=frequency=196.00:sample_rate=48000:duration=${dur.toFixed(2)},tremolo=f=0.22:d=0.45,volume=0.11[shimmer]`,
    `[noise_bed][sub][fifth][oct][shimmer]amix=inputs=5:duration=first:normalize=0,lowpass=f=680,highpass=f=40,chorus=0.5:0.7:45:0.35:0.25:2,aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo,afade=t=in:st=0:d=0.6,afade=t=out:st=${fadeOutStart}:d=0.8[bgm_out]`,
  ].join(";");

  await execFileAsync("ffmpeg", [
    "-y",
    "-filter_complex",
    bgmFilter,
    "-map",
    "[bgm_out]",
    "-c:a",
    "pcm_s16le",
    params.outputPath,
  ]);

  return { musicPath: params.outputPath, source: "ambient_cinema" };
}

/**
 * Builds the Pro Audio Mastering filtergraph:
 * - Preserves diegetic audio (`[0:a]`) from shot videos (furnace roar, sparks, metal rolling, room tone)
 * - Cleans & compresses Persian Voiceover (`High-pass 85Hz + 3.2kHz presence + broadcast compressor`)
 * - Ducks both diegetic bed and music score cleanly underneath narrator voice via `sidechaincompress`
 * - Broadcast loudness normalization (`-14 LUFS`, `-1.5 dBTP` true peak)
 */
export function buildCinemaAudioFilterGraph(params: {
  totalDurationSec: number;
  hasNarration: boolean;
  hasMusic: boolean;
  hasDiegeticAudio: boolean;
  targetLufs?: number;
  narrationAtempo?: number;
}): { filterGraph: string; mapLabel: string } {
  const dur = Math.max(0.5, params.totalDurationSec).toFixed(2);
  const fadeStart = Math.max(0.3, params.totalDurationSec - 0.6).toFixed(2);
  const lufs = params.targetLufs ?? -14;
  const atempoVal = params.narrationAtempo && params.narrationAtempo > 1.01
    ? Math.min(1.25, Math.max(0.85, params.narrationAtempo))
    : 1.0;
  const atempoStage = atempoVal > 1.01 ? `,atempo=${atempoVal.toFixed(3)}` : "";
  const chains: string[] = [];

  if (params.hasNarration) {
    // Input 0 = video+diegetic audio, Input 1 = Voiceover WAV, Input 2 (optional) = Music WAV
    chains.push(
      `[1:a]aresample=48000,aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo${atempoStage},highpass=f=85,equalizer=f=3200:t=q:w=1.2:g=3,acompressor=threshold=-20dB:ratio=3:attack=12:release=180,apad=whole_dur=${dur},atrim=0:${dur}[vo_clean]`
    );

    const mixInputs: string[] = [];
    if (params.hasDiegeticAudio && params.hasMusic) {
      chains.push(
        `[vo_clean]asplit=3[vo_mix][vo_sc1][vo_sc2]`,
        `[0:a]aresample=48000,aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo,volume=0.38[diegetic_lvl]`,
        `[diegetic_lvl][vo_sc1]sidechaincompress=threshold=0.015:ratio=4:attack=20:release=320[diegetic_duck]`,
        `[2:a]aresample=48000,aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo,volume=0.20[bgm_lvl]`,
        `[bgm_lvl][vo_sc2]sidechaincompress=threshold=0.018:ratio=5:attack=25:release=360[bgm_duck]`
      );
      mixInputs.push("[vo_mix]", "[diegetic_duck]", "[bgm_duck]");
    } else if (params.hasMusic) {
      chains.push(
        `[vo_clean]asplit=2[vo_mix][vo_sc]`,
        `[2:a]aresample=48000,aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo,volume=0.22[bgm_lvl]`,
        `[bgm_lvl][vo_sc]sidechaincompress=threshold=0.018:ratio=5:attack=25:release=360[bgm_duck]`
      );
      mixInputs.push("[vo_mix]", "[bgm_duck]");
    } else if (params.hasDiegeticAudio) {
      chains.push(
        `[vo_clean]asplit=2[vo_mix][vo_sc]`,
        `[0:a]aresample=48000,aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo,volume=0.40[diegetic_lvl]`,
        `[diegetic_lvl][vo_sc]sidechaincompress=threshold=0.015:ratio=4:attack=20:release=320[diegetic_duck]`
      );
      mixInputs.push("[vo_mix]", "[diegetic_duck]");
    } else {
      mixInputs.push("[vo_clean]");
    }

    if (mixInputs.length > 1) {
      chains.push(
        `${mixInputs.join("")}amix=inputs=${mixInputs.length}:duration=first:normalize=0:dropout_transition=2,afade=t=out:st=${fadeStart}:d=0.6,loudnorm=I=${lufs}:TP=-1.5:LRA=11[a_norm]`
      );
    } else {
      chains.push(
        `${mixInputs[0]}afade=t=out:st=${fadeStart}:d=0.6,loudnorm=I=${lufs}:TP=-1.5:LRA=11[a_norm]`
      );
    }
  } else if (params.hasMusic) {
    // Input 0 = video+diegetic audio, Input 1 = Music WAV (no voiceover)
    chains.push(
      `[0:a]aresample=48000,aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo,volume=0.72[diegetic_lvl]`,
      `[1:a]aresample=48000,aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo,volume=0.35[bgm_lvl]`,
      `[diegetic_lvl][bgm_lvl]amix=inputs=2:duration=first:normalize=0,afade=t=out:st=${fadeStart}:d=0.6,loudnorm=I=${lufs}:TP=-1.5:LRA=11[a_norm]`
    );
  } else {
    chains.push(
      `[0:a]aresample=48000,aformat=sample_fmts=fltp:sample_rates=48000:channel_layouts=stereo,afade=t=out:st=${fadeStart}:d=0.6,loudnorm=I=${lufs}:TP=-1.5:LRA=11[a_norm]`
    );
  }

  return { filterGraph: chains.join(";"), mapLabel: "[a_norm]" };
}
